import assert from 'node:assert/strict'
import test from 'node:test'
import { setToolDisplayLabelOverrides, TOOL_DISPLAY_LABELS, toolDisplayLabel } from '../../src/features/chat/tool-display'

test('every Lumbre tool has one fixed display label with a safe fallback', () => {
  assert.equal(Object.keys(TOOL_DISPLAY_LABELS).length, 151)
  assert.equal(toolDisplayLabel('read_notes'), '翻了翻纸条')
  assert.equal(toolDisplayLabel('timeline'), '翻看了日记时间线')
  assert.equal(toolDisplayLabel('get_location'), '查了查水獭位置')
  assert.equal(toolDisplayLabel('read_health_summary'), '看了看小火的健康状态')
  assert.equal(toolDisplayLabel('read_guestbook'), '翻开了告状簿')
  assert.equal(toolDisplayLabel('reply_guestbook'), '在告状簿回了句话')
  assert.equal(toolDisplayLabel('save_chat_foto'), '收藏了一张照片')
  assert.equal(toolDisplayLabel('write_travel_journal'), '续写了旅行日记')
  assert.equal(toolDisplayLabel('draw_picture'), '在小画室画画')
  assert.equal(toolDisplayLabel('log_energy_intake'), '记下了小火的吃喝')
  assert.equal(toolDisplayLabel('save_energy_goal'), '写下了今天的健康目标')
  assert.equal(toolDisplayLabel('save_grocery_item'), '写好了下次买菜清单')
  assert.equal(toolDisplayLabel('write_opening_message'), '换了一句开屏语')
  assert.equal(toolDisplayLabel('clear_opening_message'), '收起了开屏语')
  assert.equal(toolDisplayLabel('read_future_letter'), '读了读写给未来的信')
  assert.equal(toolDisplayLabel('append_future_letter'), '给未来的自己添了一段话')
  assert.equal(toolDisplayLabel('edit_future_letter_paragraph'), '改了写给未来的一段话')
  assert.equal(toolDisplayLabel('read_fire_dictionary'), '翻了翻小火辞典')
  assert.equal(toolDisplayLabel('create_fire_dictionary_entry'), '记下了一个小火词')
  assert.equal(toolDisplayLabel('update_fire_dictionary_entry'), '重新解释了一个词')
  assert.equal(toolDisplayLabel('delete_fire_dictionary_entry'), '划掉了一个旧词条')
  assert.equal(toolDisplayLabel('list_stickers'), '翻开了我们的表情册')
  assert.equal(toolDisplayLabel('send_sticker'), '递来了一张表情')
  assert.equal(toolDisplayLabel('read_summary'), '读了一张摘要')
  assert.equal(toolDisplayLabel('cedar_list_games'), '在游戏厅逛了逛')
  assert.equal(toolDisplayLabel('cedar_get_guide'), '翻开了玩法说明')
  assert.equal(toolDisplayLabel('cedar_play'), '玩了一回合')
  assert.equal(toolDisplayLabel('cedar_account'), '整理了游戏存档')
  assert.equal(toolDisplayLabel('daily_poem'), '读了今日诗词')
  assert.equal(toolDisplayLabel('hobby_add'), '往爱好角落添了新主题')
  assert.equal(toolDisplayLabel('write_windowsill_line'), '在窗台书签上写了一句话')
  assert.equal(toolDisplayLabel('kitchen_cook'), '在小厨房开了火')
  assert.equal(toolDisplayLabel('read_menu'), '翻了翻小厨房菜单')
  setToolDisplayLabelOverrides({ read_notes: '查看了自定义纸条名' })
  assert.equal(toolDisplayLabel('read_notes'), '查看了自定义纸条名')
  setToolDisplayLabelOverrides({})
  assert.equal(toolDisplayLabel('future_tool'), 'future_tool')
})
